-- -------------------------------------------------------------
--  规则模板：默认模板改名（默认规则 → 趋势跟随·均衡版）
--  背景：旧版本首次进入 /paper 会自动 seed 一套名为「默认规则」的模板，
--  名字看不出它实际用的参数；改名后与「杨永兴的“一夜持股法”」等同一层级，
--  用户能直接从名字判断规则取向。
--  本脚本幂等：可重复执行；新库由 01-schema.sql 建表，首次进页面 seed 时
--  直接使用新名字（PaperRuleService.DEFAULT_RULE_NAME）。
--  执行方式：
--    mysql -uroot -p iblog < 08-migration-paper-rule-rename.sql
-- -------------------------------------------------------------
SET NAMES utf8mb4;

UPDATE `paper_rule`
SET `name` = '趋势跟随·均衡版'
WHERE `name` = '默认规则';
